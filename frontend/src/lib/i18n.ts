export type Lang = "el" | "en";
const DICTS: Record<Lang, Record<MessageKey, string>> = { el, en };
const STORAGE_KEY = "lychnos.lang";

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "el" || saved === "en") return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.toLowerCase().startsWith("el") ? "el" : "en";
}

interface LangStore {
  lang: Lang;
  setLang: (lang: Lang) => void;
}

export const useLang = create<LangStore>((set) => ({
  lang: initialLang(),
  setLang: (lang) => {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* ignore */
    }
    document.documentElement.lang = lang;
    set({ lang });
  },
}));

document.documentElement.lang = useLang.getState().lang;

export type Vars = Record<string, string | number>;

function format(text: string, vars?: Vars): string {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Translate outside React components (toasts, helpers). */
export function t(key: MessageKey, vars?: Vars): string {
  return format(DICTS[useLang.getState().lang][key], vars);
}

/** Translate inside components; re-renders when the language changes. */
export function useT(): (key: MessageKey, vars?: Vars) => string {
  const lang = useLang((s) => s.lang);
  return (key, vars) => format(DICTS[lang][key], vars);
}

/** Locale for dates and numbers. */
export function locale(): string {
  return useLang.getState().lang === "el" ? "el-GR" : "en-GB";
}
